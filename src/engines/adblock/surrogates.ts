/** Extension path of a `$redirect` value such as `noopjs:100`, or null if we do not ship it. */
export function surrogatePath(value: string): string | null {
  const name = value.split(':')[0] ?? '';
  const file = Object.hasOwn(FILES, name) ? FILES[name] : undefined;
  return file ? `/surrogates/${file}` : null;
}
